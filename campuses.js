// Helper to look up campus by ID or name/slug
window.getCampusById = function(campusId) {
  if (!campusId) return null;
  const numId = Number(campusId);
  return window.NIGERIAN_CAMPUSES.find(c => c.id === numId || String(c.id) === String(campusId)) || null;
};

// Helper to look up campus name
window.getCampusName = function(campusId) {
  const c = window.getCampusById(campusId);
  return c ? c.name : "Alex Ekwueme Federal University, Ndufu-Alike (FUNAI)";
};

// Helper to look up campus short abbreviation
window.getCampusShort = function(campusId) {
  const c = window.getCampusById(campusId);
  return c ? c.short : "FUNAI";
};


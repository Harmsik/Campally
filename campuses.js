// Reusable live search and autocomplete for campuses across Nigeria
// Matches campus name, abbreviation (e.g. FUNAI, UNILAG, UNN, FUTO), keywords while students type
window.setupCampusAutocomplete = function({
  input,
  dropdown,
  onSelect,
  initialCampusId = null,
  showAllOption = false,
  allOptionLabel = "🏫 All Campuses (Nigeria)"
}) {
  if (!input || !dropdown) return;

  const campuses = window.NIGERIAN_CAMPUSES || [];
  let selectedCampus = null;

  function renderList(query = "") {
    const q = query.trim().toLowerCase();
    dropdown.innerHTML = "";

    if (showAllOption) {
      const allDiv = document.createElement("div");
      allDiv.className = "campus-autocomplete-item" + (!selectedCampus ? " selected" : "");
      allDiv.style.cssText = "padding:10px 14px; cursor:pointer; font-size:13px; font-weight:600; color:#2B2B2B; border-bottom:1px solid #F0EDE6; display:flex; align-items:center; justify-content:space-between;";
      allDiv.innerHTML = `<span>${allOptionLabel}</span> <span style="font-size:11px; background:#F0EDE6; padding:2px 6px; border-radius:4px; color:#666;">Nationwide</span>`;
      allDiv.addEventListener("mousedown", (e) => {
        e.preventDefault();
        selectedCampus = null;
        input.value = "";
        input.placeholder = allOptionLabel;
        dropdown.style.display = "none";
        if (typeof onSelect === "function") onSelect(null);
      });
      dropdown.appendChild(allDiv);
    }

    let matches = [];
    if (!q) {
      // Show top campuses when input is blank
      matches = campuses.slice(0, 15);
    } else {
      matches = campuses.filter((c) => {
        const short = (c.short || "").toLowerCase();
        const name = (c.name || "").toLowerCase();
        return short.includes(q) || name.includes(q);
      });

      // Rank exact abbreviation matches higher (e.g. typing 'funai' or 'unn')
      matches.sort((a, b) => {
        const aShort = (a.short || "").toLowerCase();
        const bShort = (b.short || "").toLowerCase();
        if (aShort === q) return -1;
        if (bShort === q) return 1;
        if (aShort.startsWith(q) && !bShort.startsWith(q)) return -1;
        if (!aShort.startsWith(q) && bShort.startsWith(q)) return 1;
        return 0;
      });
    }

    if (matches.length === 0) {
      const emptyDiv = document.createElement("div");
      emptyDiv.style.cssText = "padding:12px 14px; color:#888; font-size:13px; text-align:center;";
      emptyDiv.innerHTML = `No campus matching "<strong>${query}</strong>". Check spelling or abbreviation.`;
      dropdown.appendChild(emptyDiv);
      dropdown.style.display = "block";
      return;
    }

    matches.slice(0, 30).forEach((c) => {
      const item = document.createElement("div");
      item.className = "campus-autocomplete-item" + (selectedCampus && selectedCampus.id === c.id ? " selected" : "");
      item.style.cssText = "padding:10px 14px; cursor:pointer; font-size:13px; color:#2B2B2B; border-bottom:1px solid #F5F3EF; display:flex; align-items:center; justify-content:space-between; gap:8px;";

      // Highlight matching keyword
      let displayName = c.name;
      let displayShort = c.short || "";
      if (q) {
        const regex = new RegExp(`(${q.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")})`, "gi");
        displayName = displayName.replace(regex, `<span style="background:#FFE6E1; color:#E8553D; font-weight:700;">$1</span>`);
        displayShort = displayShort.replace(regex, `<span style="background:#FFE6E1; color:#E8553D; font-weight:700;">$1</span>`);
      }

      item.innerHTML = `
        <div style="flex:1; overflow:hidden; text-overflow:ellipsis; white-space:nowrap;">
          <span style="margin-right:6px;">🏫</span>
          <span>${displayName}</span>
        </div>
        <span style="flex:0 0 auto; background:#FDF1EE; color:#E8553D; font-weight:700; font-size:11px; padding:2px 8px; border-radius:6px; border:1px solid #FCD8D0;">${displayShort}</span>
      `;

      item.addEventListener("mousedown", (e) => {
        e.preventDefault();
        selectedCampus = c;
        input.value = c.name;
        dropdown.style.display = "none";
        if (typeof onSelect === "function") onSelect(c);
      });

      dropdown.appendChild(item);
    });

    dropdown.style.display = "block";
  }

  // Pre-select if initial campus provided
  if (initialCampusId) {
    const found = window.getCampusById(initialCampusId);
    if (found) {
      selectedCampus = found;
      input.value = found.name;
    }
  }

  input.addEventListener("focus", () => {
    renderList(input.value);
  });

  input.addEventListener("input", () => {
    renderList(input.value);
    if (!input.value.trim() && showAllOption) {
      selectedCampus = null;
      if (typeof onSelect === "function") onSelect(null);
    }
  });

  input.addEventListener("keydown", (e) => {
    if (e.key === "Escape") {
      dropdown.style.display = "none";
    }
  });

  document.addEventListener("click", (e) => {
    if (!input.contains(e.target) && !dropdown.contains(e.target)) {
      dropdown.style.display = "none";
    }
  });

  return {
    setCampus: (campusId) => {
      if (!campusId) {
        selectedCampus = null;
        input.value = "";
        return;
      }
      const c = window.getCampusById(campusId);
      if (c) {
        selectedCampus = c;
        input.value = c.name;
      }
    },
    getSelectedCampus: () => selectedCampus
  };
};

